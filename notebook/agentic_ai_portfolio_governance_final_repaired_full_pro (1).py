def equal_weight_weights(r):
    n = r.shape[1]
    return pd.Series(np.ones(n) / n, index=r.columns)


def inverse_volatility_weights(r):
    vol = r.std().replace(0, np.nan)
    inv = (1 / vol).replace([np.inf, -np.inf], np.nan).fillna(0)
    if inv.sum() <= 0:
        return equal_weight_weights(r)
    return inv / inv.sum()


def min_variance_weights(r, max_weight=CONFIG["max_weight"]):
    cols = list(r.columns)
    n = len(cols)
    if n == 0:
        return pd.Series(dtype=float)

    max_w = max(max_weight, 1 / n + 1e-6)
    cov = r.cov().values
    w = cp.Variable(n)
    objective = cp.Minimize(cp.quad_form(w, cov))
    constraints = [cp.sum(w) == 1, w >= 0, w <= max_w]
    problem = cp.Problem(objective, constraints)

    for solver in ["CLARABEL", "ECOS", "OSQP", "SCS"]:
        if solver not in cp.installed_solvers():
            continue
        try:
            problem.solve(solver=solver, verbose=False)
            if w.value is not None:
                weights = np.maximum(np.asarray(w.value).flatten(), 0)
                if weights.sum() > 0:
                    return pd.Series(weights / weights.sum(), index=cols)
        except Exception:
            continue

    return inverse_volatility_weights(r)


def graph_centrality_penalty(r, threshold=CONFIG["graph_corr_threshold"]):
    corr = r.corr().fillna(0)
    tickers = list(corr.columns)
    graph = nx.Graph()
    graph.add_nodes_from(tickers)

    for i, a in enumerate(tickers):
        for j, b in enumerate(tickers):
            if i < j:
                value = abs(corr.loc[a, b])
                if value >= threshold:
                    graph.add_edge(a, b, weight=value)

    if graph.number_of_edges() == 0:
        return pd.Series(np.zeros(len(tickers)), index=tickers)

    try:
        centrality = nx.eigenvector_centrality(graph, max_iter=1000, weight="weight")
    except Exception:
        centrality = nx.degree_centrality(graph)

    penalty = pd.Series(centrality).reindex(tickers).fillna(0)
    return safe_min_max_scale(penalty)


def daily_target_from_annual(target_annual_return):
    if target_annual_return is None:
        return None
    return (1 + target_annual_return) ** (1 / TRADING_DAYS) - 1


def optimize_cvar_weights(
    r,
    alpha=CONFIG["cvar_alpha"],
    max_weight=CONFIG["max_weight"],
    return_tradeoff=CONFIG["return_tradeoff"],
    graph_penalty=None,
    graph_lambda=0.0,
    target_annual_return=CONFIG["target_annual_return"],
):
    clean = r.dropna(how="any")
    cols = list(clean.columns)
    T, n = clean.shape

    if T == 0 or n == 0:
        return pd.Series(dtype=float)

    R = clean.values
    mu = clean.mean().values
    max_w = max(max_weight, 1 / n + 1e-6)

    w = cp.Variable(n)
    z = cp.Variable()
    u = cp.Variable(T)

    losses = -R @ w
    cvar_expr = z + (1 / ((1 - alpha) * T)) * cp.sum(u)
    objective_expr = cvar_expr - return_tradeoff * (mu @ w)

    if graph_penalty is not None and graph_lambda > 0:
        g = pd.Series(graph_penalty).reindex(cols).fillna(0).values
        objective_expr += graph_lambda * (g @ w)

    constraints = [
        u >= losses - z,
        u >= 0,
        cp.sum(w) == 1,
        w >= 0,
        w <= max_w,
    ]

    target_daily = daily_target_from_annual(target_annual_return)
    if target_daily is not None:
        constraints_with_target = constraints + [mu @ w >= target_daily]
    else:
        constraints_with_target = constraints

    def solve_problem(constraints_to_use, target_used):
        problem = cp.Problem(cp.Minimize(objective_expr), constraints_to_use)
        for solver in ["CLARABEL", "ECOS", "SCS"]:
            if solver not in cp.installed_solvers():
                continue
            try:
                problem.solve(solver=solver, verbose=False)
                if w.value is not None:
                    weights = np.maximum(np.asarray(w.value).flatten(), 0)
                    if weights.sum() > 0:
                        result = pd.Series(weights / weights.sum(), index=cols)
                        result.attrs["solver"] = solver
                        result.attrs["target_return_constraint_used"] = target_used
                        return result
            except Exception:
                continue
        return None

    solution = solve_problem(constraints_with_target, target_used=True)
    if solution is not None:
        return solution

    solution = solve_problem(constraints, target_used=False)
    if solution is not None:
        solution.attrs["target_return_fallback"] = True
        return solution

    fallback = inverse_volatility_weights(clean)
    fallback.attrs["solver"] = "inverse_volatility_fallback"
    return fallback


def portfolio_returns(r, weights):
    weights = pd.Series(weights).reindex(r.columns).fillna(0)
    if weights.sum() <= 0:
        return pd.Series(index=r.index, dtype=float)
    weights = weights / weights.sum()
    return r.dot(weights)

