"""## 14. Adaptive Graph-CVaR Imported from the Evaluation Logic

The evaluation notebook's stronger G-CVaR behavior comes from an important idea: the graph penalty should be **adaptive**, not always active.

So this section adds a new strategy:

`adaptive_graph_cvar`

It works like this:

1. Compute an instability score `I_t`.
2. Convert `I_t` into an adaptive graph-penalty gate `lambda_t`.
3. During calm periods, Graph-CVaR behaves close to standard CVaR.
4. During stress periods, graph centrality is penalized more strongly.

This is more aligned with the thesis claim than a permanently strong graph penalty.

"""

# ============================================================
# 14.1 Adaptive Graph-CVaR Rolling Strategy
# ============================================================

def adaptive_graph_cvar_returns(
    r_all,
    split_date,
    lookback_days=756,
    rebalance_frequency="QE",
    base_graph_lambda=CONFIG["graph_lambda"],
    target_annual_return=CONFIG["target_annual_return"],
):
    """
    Rolling Graph-CVaR with sigmoid-gated graph penalty.

    This ports the useful idea from evaluations.ipynb:
    graph penalty should be sparse and stronger only when instability is high.
    """
    r_all = r_all.dropna(how="any")
    test_dates = r_all.loc[split_date:].index
    if len(test_dates) == 0:
        return pd.Series(dtype=float), pd.DataFrame(), pd.DataFrame()

    instability_panel = compute_instability_panel(r_all)
    rebalance_dates = pd.Series(test_dates, index=test_dates).resample(rebalance_frequency).first().dropna().tolist()
    if test_dates[0] not in rebalance_dates:
        rebalance_dates = [test_dates[0]] + rebalance_dates
    rebalance_dates = sorted(pd.to_datetime(rebalance_dates))

    pieces = []
    weight_records = []
    regime_records = []

    for i, start in enumerate(rebalance_dates):
        end = rebalance_dates[i + 1] if i + 1 < len(rebalance_dates) else test_dates[-1] + pd.Timedelta(days=1)

        train_end_position = r_all.index.get_indexer([start], method="ffill")[0]
        train_start_position = max(0, train_end_position - lookback_days)

        r_train = r_all.iloc[train_start_position:train_end_position]
        r_period = r_all.loc[(r_all.index >= start) & (r_all.index < end)]

        if len(r_train) < 200 or len(r_period) == 0:
            continue

        if len(instability_panel.loc[:start]) > 0:
            current_signal = instability_panel.loc[:start].iloc[-1]
            instability_index = float(current_signal["instability_index"])
            lambda_gate = float(current_signal["lambda_t"])
            regime = str(current_signal["regime"])
        else:
            instability_index = 0.0
            lambda_gate = 0.0
            regime = "Calm"

        active_graph_lambda = base_graph_lambda * lambda_gate
        g_penalty = graph_centrality_penalty(r_train, threshold=CONFIG["graph_corr_threshold"])

        weights = optimize_cvar_weights(
            r_train,
            alpha=CONFIG["cvar_alpha"],
            max_weight=CONFIG["max_weight"],
            return_tradeoff=CONFIG["return_tradeoff"],
            graph_penalty=g_penalty,
            graph_lambda=active_graph_lambda,
            target_annual_return=target_annual_return,
        )

        period_returns = portfolio_returns(r_period, weights)
        pieces.append(period_returns)
        weight_records.append(pd.Series(weights, name=start))

