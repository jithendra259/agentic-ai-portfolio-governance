def build_hitl_ticker_records(hitl_logs):
    ticker_rows = []
    if hitl_logs is None or hitl_logs.empty:
        return pd.DataFrame()

    for _, log in hitl_logs.iterrows():
        universe = log["universe"]
        date = pd.to_datetime(log["rebalance_date"])
        weight_hist = ADAPTIVE_WEIGHT_HISTORY.get(universe, pd.DataFrame()) if "ADAPTIVE_WEIGHT_HISTORY" in globals() else pd.DataFrame()
        if weight_hist is None or weight_hist.empty:
            continue

        proposed = nearest_weight_row(weight_hist, date)
        if proposed.empty:
            continue
        proposed = proposed / proposed.sum()

        if log["operator_action"] == "Constrain":
            adopted = cap_and_renormalize_weights(proposed, cap=CONFIG.get("hitl_weight_cap_after_constrain", 0.08))
        elif log["operator_action"] == "Reject":
            previous_date = pd.to_datetime(weight_hist.index)[pd.to_datetime(weight_hist.index) < date]
            if len(previous_date) > 0:
                adopted = weight_hist.loc[previous_date[-1]].dropna()
                adopted = adopted / adopted.sum()
            else:
                adopted = proposed.copy()
        else:
            adopted = proposed.copy()

        network_risk = compute_ticker_network_risk_at_date(universe, date).reindex(proposed.index).fillna(0)

        for ticker in proposed.index:
            ticker_rows.append({
                "log_id": log["log_id"],
                "universe": universe,
                "universe_label": log["universe_label"],
                "rebalance_date": date,
                "operator_action": log["operator_action"],
                "regime": log["regime"],
                "instability_index": log["instability_index"],
                "lambda_t": log["lambda_t"],
                "ticker": ticker,
                "network_risk": float(network_risk.get(ticker, 0.0)),
                "proposed_weight": float(proposed.get(ticker, 0.0)),
                "adopted_weight": float(adopted.get(ticker, 0.0)),
                "weight_delta": float(adopted.get(ticker, 0.0) - proposed.get(ticker, 0.0)),
                "abs_weight_delta": float(abs(adopted.get(ticker, 0.0) - proposed.get(ticker, 0.0))),
                "risk_weight_product_proposed": float(network_risk.get(ticker, 0.0) * proposed.get(ticker, 0.0)),
                "risk_weight_product_adopted": float(network_risk.get(ticker, 0.0) * adopted.get(ticker, 0.0)),
            })

    out = pd.DataFrame(ticker_rows)
    if not out.empty:
        out = out.sort_values(["universe", "rebalance_date", "ticker"]).reset_index(drop=True)
    return out


