TRADING_DAYS = CONFIG["trading_days"]


def geometric_annual_return(r, periods=TRADING_DAYS):
    r = pd.Series(r).dropna()
    if len(r) == 0:
        return np.nan
    growth = float((1 + r).prod())
    if growth <= 0:
        return np.nan
    return growth ** (periods / len(r)) - 1


def annualized_volatility(r, periods=TRADING_DAYS):
    r = pd.Series(r).dropna()
    return r.std() * np.sqrt(periods) if len(r) else np.nan


def compute_drawdown(r):
    r = pd.Series(r).dropna()
    wealth = (1 + r).cumprod()
    peak = wealth.cummax()
    return wealth / peak - 1


def compute_max_drawdown(r):
    dd = compute_drawdown(r)
    return dd.min() if len(dd) else np.nan


def historical_var(r, alpha=0.95):
    r = pd.Series(r).dropna()
    return r.quantile(1 - alpha) if len(r) else np.nan


def historical_cvar(r, alpha=0.95):
    r = pd.Series(r).dropna()
    if len(r) == 0:
        return np.nan
    var = historical_var(r, alpha)
    return r[r <= var].mean()


def historical_cvar_loss(r, alpha=0.95):
    cvar = historical_cvar(r, alpha=alpha)
    return -cvar if pd.notna(cvar) else np.nan


def downside_deviation(r, target=0.0, periods=TRADING_DAYS):
    r = pd.Series(r).dropna()
    if len(r) == 0:
        return np.nan
    downside = np.minimum(r - target, 0.0)
    return np.sqrt(np.mean(downside ** 2)) * np.sqrt(periods)


def sortino_ratio(r, risk_free_rate=CONFIG["risk_free_rate"], periods=TRADING_DAYS):
    r = pd.Series(r).dropna()
    if len(r) == 0:
        return np.nan
    ann_return = geometric_annual_return(r, periods=periods)
    daily_rf = (1 + risk_free_rate) ** (1 / periods) - 1
    dd = downside_deviation(r, target=daily_rf, periods=periods)
    return (ann_return - risk_free_rate) / dd if pd.notna(dd) and dd > 0 else np.nan


def portfolio_metrics(r, risk_free_rate=CONFIG["risk_free_rate"]):
    r = pd.Series(r).dropna()
    if len(r) == 0:
        return {}
    ann_return = geometric_annual_return(r)
    ann_vol = annualized_volatility(r)
    sharpe = (ann_return - risk_free_rate) / ann_vol if pd.notna(ann_vol) and ann_vol > 0 else np.nan
    cvar = historical_cvar(r, CONFIG["cvar_alpha"])
    sortino = sortino_ratio(r, risk_free_rate=risk_free_rate)
    return {
        "annual_return": ann_return,
        "annual_volatility": ann_vol,
        "volatility": ann_vol,  # alias used by later score tables
        "sharpe_ratio": sharpe,
        "sortino_ratio": sortino,
        "historical_var_95": historical_var(r, CONFIG["cvar_alpha"]),
        "historical_cvar_95": cvar,
        "historical_cvar_loss_95": -cvar if pd.notna(cvar) else np.nan,
        "max_drawdown": compute_max_drawdown(r),
        "observations": len(r),
    }


def rolling_sharpe(r, window=CONFIG["rolling_window"], risk_free_rate=CONFIG["risk_free_rate"]):
    daily_rf = (1 + risk_free_rate) ** (1 / TRADING_DAYS) - 1
    mean = (r - daily_rf).rolling(window).mean() * TRADING_DAYS
    vol = r.rolling(window).std() * np.sqrt(TRADING_DAYS)
    return mean / vol


def rolling_cvar(r, window=CONFIG["rolling_window"], alpha=CONFIG["cvar_alpha"]):
    return r.rolling(window).apply(lambda x: historical_cvar(pd.Series(x), alpha), raw=False)


def safe_min_max_scale(series):
    s = pd.Series(series).astype(float)
    if s.empty or s.max() == s.min():
        return pd.Series(np.zeros(len(s)), index=s.index)
    return (s - s.min()) / (s.max() - s.min())

