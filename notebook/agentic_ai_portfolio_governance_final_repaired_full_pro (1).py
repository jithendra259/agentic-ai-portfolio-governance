def plot_crisis_only_adaptive_comparison(show=True):
    """Crisis/active-window test: Adaptive G-CVaR should be judged where lambda is active."""
    if "ADAPTIVE_REGIME_LOGS" not in globals() or "BACKTEST_RETURNS" not in globals():
        print("Need ADAPTIVE_REGIME_LOGS and BACKTEST_RETURNS for crisis-only comparison.")
        return None

    rows = []
    strategies = ["equal_weight", "cvar_optimized", "graph_cvar_optimized", "adaptive_graph_cvar"]
    for universe, log in ADAPTIVE_REGIME_LOGS.items():
        if log is None or len(log) == 0:
            continue
        lam_col = "lambda_gate" if "lambda_gate" in log.columns else ("lambda_t" if "lambda_t" in log.columns else None)
        if lam_col is None:
            continue
        active_dates = pd.to_datetime(log.loc[log[lam_col] > 0.50, "rebalance_date"])
        if active_dates.empty:
            continue
        # Use +/- one rebalance month around active dates as a crisis-active evaluation mask.
        active_windows = []
        for d in active_dates:
            active_windows.append((d - pd.Timedelta(days=5), d + pd.Timedelta(days=95)))
        for strategy in strategies:
            r = BACKTEST_RETURNS.get((universe, strategy), pd.Series(dtype=float))
            if r is None or len(r) == 0:
                continue
            r = r.dropna().copy()
            mask = pd.Series(False, index=r.index)
            for start, end in active_windows:
                mask = mask | ((r.index >= start) & (r.index <= end))
            crisis_r = r.loc[mask]
            if len(crisis_r) < 10:
                continue
            m = portfolio_metrics(crisis_r)
            rows.append({
                "universe": universe,
                "strategy": strategy,
                "strategy_label": algorithm_label(strategy) if "algorithm_label" in globals() else strategy,
                "active_days": len(crisis_r),
                "active_terminal_value": 100000.0 * float((1 + crisis_r).prod()),
                "active_return": float((1 + crisis_r).prod() - 1),
                "active_cvar_loss": m.get("historical_cvar_loss_95", np.nan),
                "active_max_drawdown": m.get("max_drawdown", np.nan),
                "active_sharpe": m.get("sharpe_ratio", np.nan),
            })
    crisis_df = pd.DataFrame(rows)
    if crisis_df.empty:
        print("No active/crisis windows found using λ > 0.50. This itself suggests the adaptive gate is sparse.")
        return None
    crisis_df.to_csv(TABLE_DIR / "adaptive_gcvar_crisis_active_window_results.csv", index=False)

    pivot = crisis_df.pivot_table(index="strategy_label", columns="universe", values="active_cvar_loss", aggfunc="first")
