def cap_and_renormalize_weights(weights, cap=0.08):
    # Cap weights and redistribute excess across uncapped names.
    w = pd.Series(weights).dropna().astype(float).clip(lower=0)
    if w.empty or w.sum() <= 0:
        return w
    w = w / w.sum()

    for _ in range(20):
        over = w > cap
        if not over.any():
            break
        excess = (w[over] - cap).sum()
        w[over] = cap
        under = ~over
        if under.any() and w[under].sum() > 0:
            w[under] = w[under] + excess * (w[under] / w[under].sum())
        else:
            break
    return (w / w.sum()).fillna(0)


def nearest_weight_row(weight_df, date):
    # Return the most recent weight vector at or before date.
    if weight_df is None or weight_df.empty:
        return pd.Series(dtype=float)
    wdf = weight_df.copy()
    wdf.index = pd.to_datetime(wdf.index)
    date = pd.to_datetime(date)
    eligible = wdf.loc[wdf.index <= date]
    if eligible.empty:
        return wdf.iloc[0].dropna()
    return eligible.iloc[-1].dropna()


def trailing_returns_for_date(universe, date, lookback_days=756):
    # Return trailing universe returns ending before date.
    tickers = [t for t in WORKING_UNIVERSES[universe] if t in returns.columns]
    r = returns[tickers].dropna(how="any")
    date = pd.to_datetime(date)
    hist = r.loc[r.index < date]
    if len(hist) > lookback_days:
        hist = hist.iloc[-lookback_days:]
    return hist


def compute_ticker_network_risk_at_date(universe, date):
    # Compute ticker-level network centrality risk using only trailing data.
    hist = trailing_returns_for_date(universe, date)
    if hist.empty:
        return pd.Series(dtype=float)
    risk = graph_centrality_penalty(hist, threshold=CONFIG.get("graph_corr_threshold", 0.55))
    return risk.reindex(hist.columns).fillna(0)


def sample_hitl_action(row):
    # Deterministic sample operator decision based only on contemporaneous governance data.
    lam = row.get("lambda_t", row.get("lambda_gate", 0.0))
    inst = row.get("instability_index", 0.0)
    turnover = row.get("proposed_l1_turnover", 0.0)
    risk_exposure = row.get("proposed_graph_risk_exposure", 0.0)
    max_weight = row.get("proposed_max_weight", 0.0)
    effective_n = row.get("proposed_effective_n", np.nan)

    if (lam >= 0.70) or (inst >= 1.25 and risk_exposure >= 0.08) or (max_weight > CONFIG.get("max_weight", 0.25)):
        return "Constrain", "High instability or high graph-risk exposure requires tighter concentration control."
    if (turnover >= CONFIG.get("hitl_turnover_trigger", 0.40)) and (inst >= 0.75):
        return "Reject", "Turnover is high during unstable conditions, so the operator reverts to previous weights."
    if pd.notna(effective_n) and effective_n < 4 and inst >= 0.75:
        return "Constrain", "Effective diversification is low during elevated instability."
    return "Approve", "Risk trigger is acceptable, so the proposed adaptive G-CVaR allocation is approved."


def build_sample_hitl_logs():
    rows = []

    for universe in WORKING_UNIVERSES:
        regime_log = ADAPTIVE_REGIME_LOGS.get(universe, pd.DataFrame()) if "ADAPTIVE_REGIME_LOGS" in globals() else pd.DataFrame()
        weight_hist = ADAPTIVE_WEIGHT_HISTORY.get(universe, pd.DataFrame()) if "ADAPTIVE_WEIGHT_HISTORY" in globals() else pd.DataFrame()

        if regime_log is None or regime_log.empty or weight_hist is None or weight_hist.empty:
            continue

        regime_log = regime_log.copy()
        if "rebalance_date" not in regime_log.columns:
            continue
        regime_log["rebalance_date"] = pd.to_datetime(regime_log["rebalance_date"])
        weight_hist = weight_hist.copy()
        weight_hist.index = pd.to_datetime(weight_hist.index)

        previous_weights = pd.Series(dtype=float)

        for _, rec in regime_log.iterrows():
            date = pd.to_datetime(rec["rebalance_date"])
            proposed = nearest_weight_row(weight_hist, date)
            if proposed.empty:
                continue
            proposed = proposed / proposed.sum()

            network_risk = compute_ticker_network_risk_at_date(universe, date).reindex(proposed.index).fillna(0)
            proposed_graph_exposure = float((proposed * network_risk).sum())
            proposed_max_weight = float(proposed.max())
            proposed_top_ticker = str(proposed.idxmax())
            proposed_top_weight = float(proposed.max())
            highest_risk_ticker = str(network_risk.idxmax()) if not network_risk.empty else ""
            highest_risk_value = float(network_risk.max()) if not network_risk.empty else np.nan

            if previous_weights.empty:
                proposed_l1_turnover = 0.0
            else:
                aligned_prev = previous_weights.reindex(proposed.index).fillna(0)
                proposed_l1_turnover = float((proposed - aligned_prev).abs().sum())

            hhi = weight_hhi(proposed)
            effective_n = effective_n_from_hhi(hhi)

            row = {
                "log_id": f"{universe}_{date.strftime('%Y%m%d')}",
                "universe": universe,
                "universe_label": UNIVERSE_LABELS.get(universe, universe),
                "rebalance_date": date,
                "instability_index": float(rec.get("instability_index", np.nan)),
                "lambda_t": float(rec.get("lambda_gate", rec.get("lambda_t", np.nan))),
                "active_graph_lambda": float(rec.get("active_graph_lambda", np.nan)),
                "regime": str(rec.get("regime", "Unknown")),
                "proposed_l1_turnover": proposed_l1_turnover,
                "proposed_graph_risk_exposure": proposed_graph_exposure,
                "proposed_hhi": hhi,
                "proposed_effective_n": effective_n,
                "proposed_max_weight": proposed_max_weight,
                "proposed_top_ticker": proposed_top_ticker,
                "proposed_top_weight": proposed_top_weight,
                "highest_risk_ticker": highest_risk_ticker,
                "highest_risk_value": highest_risk_value,
                "hitl_required": bool(
                    (float(rec.get("lambda_gate", rec.get("lambda_t", 0))) >= CONFIG.get("hitl_lambda_trigger", 0.50))
                    or (proposed_l1_turnover >= CONFIG.get("hitl_turnover_trigger", 0.40))
                    or (float(rec.get("instability_index", 0)) >= CONFIG.get("instability_threshold", 1.0))
                ),
            }

            action, reason = sample_hitl_action(row)
            row["operator_action"] = action
            row["operator_reason"] = reason

            if action == "Reject" and not previous_weights.empty:
                adopted = previous_weights.reindex(proposed.index).fillna(0)
                if adopted.sum() > 0:
                    adopted = adopted / adopted.sum()
            elif action == "Constrain":
                adopted = cap_and_renormalize_weights(proposed, cap=CONFIG.get("hitl_weight_cap_after_constrain", 0.08))
            else:
                adopted = proposed.copy()

            adopted = adopted.reindex(proposed.index).fillna(0)
            if adopted.sum() > 0:
                adopted = adopted / adopted.sum()

            row["adopted_hhi"] = weight_hhi(adopted)
            row["adopted_effective_n"] = effective_n_from_hhi(row["adopted_hhi"])
            row["adopted_graph_risk_exposure"] = float((adopted * network_risk).sum()) if not network_risk.empty else np.nan
            row["adopted_max_weight"] = float(adopted.max()) if not adopted.empty else np.nan
            row["weight_change_from_hitl"] = float((adopted - proposed).abs().sum()) if not adopted.empty else 0.0

            rows.append(row)
            previous_weights = adopted.copy()

    logs = pd.DataFrame(rows)
    if not logs.empty:
        logs = logs.sort_values(["universe", "rebalance_date"]).reset_index(drop=True)
    return logs


