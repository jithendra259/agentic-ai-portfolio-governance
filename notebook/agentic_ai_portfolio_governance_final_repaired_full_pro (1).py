def bootstrap_strategy_sharpe(strategy, n_iter=BOOTSTRAP_ITERATIONS, seed=BOOTSTRAP_RANDOM_SEED):
    # Pool daily strategy returns across universes, then block bootstrap by month to preserve some time structure.
    monthly_blocks = []
    for universe in WORKING_UNIVERSES:
        r = _safe_strategy_returns(universe, strategy)
        if r.empty:
            continue
        block = r.to_frame("return")
        block["month"] = block.index.to_period("M")
        for _, group in block.groupby("month"):
            monthly_blocks.append(group["return"].values)

    if len(monthly_blocks) < 5:
        return np.nan, np.nan, np.nan

    rng = np.random.default_rng(seed)
    boot = np.empty(n_iter)
    for i in range(n_iter):
        sampled_blocks = rng.choice(len(monthly_blocks), size=len(monthly_blocks), replace=True)
        sampled = np.concatenate([monthly_blocks[j] for j in sampled_blocks])
        m = portfolio_metrics(pd.Series(sampled))
        boot[i] = m.get("sharpe_ratio", np.nan)
    boot = boot[np.isfinite(boot)]
    return float(np.nanmean(boot)), float(np.nanpercentile(boot, 2.5)), float(np.nanpercentile(boot, 97.5))


