def _monthly_returns_from_strategy(strategy):
    pieces = []
    for universe in WORKING_UNIVERSES:
        r = _safe_strategy_returns(universe, strategy)
        if not r.empty:
            m = (1 + r).resample("ME").prod() - 1
            pieces.append(m.rename(universe))
    if not pieces:
        return pd.Series(dtype=float)
    return pd.concat(pieces, axis=1).stack().dropna()


