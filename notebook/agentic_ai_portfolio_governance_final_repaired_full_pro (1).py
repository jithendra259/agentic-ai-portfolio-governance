def fixed_quarterly_graph_cvar_returns(r_all, split_date, lookback_days=756, rebalance_frequency="QE"):
    r_all = r_all.dropna(how="any")
    test_dates = r_all.loc[split_date:].index
    if len(test_dates) == 0:
        return pd.Series(dtype=float), pd.DataFrame()

    rebalance_dates = pd.Series(test_dates, index=test_dates).resample(rebalance_frequency).first().dropna().tolist()
    if test_dates[0] not in rebalance_dates:
        rebalance_dates = [test_dates[0]] + rebalance_dates
    rebalance_dates = sorted(pd.to_datetime(rebalance_dates))

    pieces = []
    weight_records = []

    for i, start in enumerate(rebalance_dates):
        end = rebalance_dates[i + 1] if i + 1 < len(rebalance_dates) else test_dates[-1] + pd.Timedelta(days=1)
        train_end_position = r_all.index.get_indexer([start], method="ffill")[0]
        train_start_position = max(0, train_end_position - lookback_days)
        r_train = r_all.iloc[train_start_position:train_end_position]
        r_period = r_all.loc[(r_all.index >= start) & (r_all.index < end)]

        if len(r_train) < 200 or len(r_period) == 0:
            continue

        g_penalty = graph_centrality_penalty(r_train, threshold=CONFIG["graph_corr_threshold"])
        weights = optimize_cvar_weights(
            r_train,
            alpha=CONFIG["cvar_alpha"],
            max_weight=CONFIG["max_weight"],
            return_tradeoff=CONFIG["return_tradeoff"],
            graph_penalty=g_penalty,
            graph_lambda=CONFIG["graph_lambda"],
            target_annual_return=CONFIG["target_annual_return"],
        )

        period_returns = portfolio_returns(r_period, weights)
        pieces.append(period_returns)
        weight_records.append(pd.Series(weights, name=start))

    if not pieces:
        return pd.Series(dtype=float), pd.DataFrame()

    return pd.concat(pieces).sort_index(), pd.DataFrame(weight_records)

