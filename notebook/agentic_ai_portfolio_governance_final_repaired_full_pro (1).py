def build_holdings_matrix_from_csv(path, universe_tickers=None, asof_date=None):
    """
    Optional 13F-style holdings loader.
    Expected CSV columns: filing_date, manager_id, ticker, market_value
    This function is look-ahead safe if the filing_date already reflects public availability.
    """
    path = Path(path)
    if not path.exists():
        return pd.DataFrame()

    h = pd.read_csv(path)
    required = {"filing_date", "manager_id", "ticker", "market_value"}
    missing = required.difference(h.columns)
    if missing:
        raise ValueError(f"Institutional holdings CSV missing columns: {sorted(missing)}")

    h["filing_date"] = pd.to_datetime(h["filing_date"])
    h["ticker"] = h["ticker"].astype(str).str.upper().str.strip()

    if asof_date is not None:
        asof_date = pd.to_datetime(asof_date)
        h = h[h["filing_date"] <= asof_date]
        if h.empty:
            return pd.DataFrame()
        latest_date = h["filing_date"].max()
        h = h[h["filing_date"] == latest_date]

    if universe_tickers is not None:
        universe_tickers = [str(t).upper().strip() for t in universe_tickers]
        h = h[h["ticker"].isin(universe_tickers)]

    if h.empty:
        return pd.DataFrame()

    H = h.pivot_table(
        index="manager_id",
        columns="ticker",
        values="market_value",
        aggfunc="sum",
        fill_value=0.0,
    )

    row_sums = H.sum(axis=1).replace(0, np.nan)
    H = H.div(row_sums, axis=0).fillna(0.0)
    return H


def institutional_coownership_penalty(holdings_matrix, target_tickers=None):
    """Compute normalized centrality from manager-by-ticker holdings matrix."""
    H = pd.DataFrame(holdings_matrix).copy()
    if H.empty:
        return pd.Series(dtype=float)

    A = H.T @ H
    A = pd.DataFrame(A, index=H.columns, columns=H.columns)
    np.fill_diagonal(A.values, 0.0)

    keep = A.sum(axis=1) > 0
    A = A.loc[keep, keep]
    if A.empty:
        out = pd.Series(0.0, index=target_tickers if target_tickers is not None else H.columns)
        return out

    G = nx.from_pandas_adjacency(A)
    try:
        cen = nx.eigenvector_centrality_numpy(G, weight="weight")
    except Exception:
        cen = dict(G.degree(weight="weight"))

    penalty = pd.Series(cen, dtype=float)
    if penalty.max() > penalty.min():
        penalty = (penalty - penalty.min()) / (penalty.max() - penalty.min())
    else:
        penalty[:] = 0.0

    if target_tickers is not None:
        penalty = penalty.reindex(target_tickers).fillna(0.0)

    penalty.name = "institutional_coownership_penalty"
    return penalty


def get_graph_penalty_for_universe(r_train, universe=None, asof_date=None):
    """
    Single graph-penalty router.
    If institutional 13F holdings are enabled and available, use them.
    Otherwise use the restored correlation-network proxy.
    """
    tickers = list(r_train.columns)

    if CONFIG.get("use_institutional_13f_graph", False):
        H = build_holdings_matrix_from_csv(
            CONFIG.get("institutional_holdings_csv", "data/institutional_13f_holdings.csv"),
            universe_tickers=tickers,
            asof_date=asof_date,
        )
        p = institutional_coownership_penalty(H, target_tickers=tickers)
        if not p.empty and p.abs().sum() > 0:
            return p.reindex(tickers).fillna(0.0)

    # Fallback: existing price-correlation graph proxy
    return graph_centrality_penalty(r_train, threshold=CONFIG.get("graph_corr_threshold", 0.45)).reindex(tickers).fillna(0.0)

