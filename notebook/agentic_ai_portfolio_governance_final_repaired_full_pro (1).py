def period_returns_for_log(log, adopted_weights):
    universe = log["universe"]
    date = pd.to_datetime(log["rebalance_date"])
    r_u = get_universe_returns(universe)
    if r_u.empty:
        return pd.Series(dtype=float)

    same_u = sample_hitl_logs_df[sample_hitl_logs_df["universe"] == universe].sort_values("rebalance_date")
    future_dates = pd.to_datetime(same_u.loc[pd.to_datetime(same_u["rebalance_date"]) > date, "rebalance_date"])
    end = future_dates.iloc[0] if len(future_dates) else r_u.index.max() + pd.Timedelta(days=1)

    r_period = r_u.loc[(r_u.index >= date) & (r_u.index < end)]
    if r_period.empty:
        return pd.Series(dtype=float)
    w = pd.Series(adopted_weights).reindex(r_period.columns).fillna(0)
    if w.sum() > 0:
        w = w / w.sum()
    return portfolio_returns(r_period, w)


def build_hitl_impact_table():
    rows = []
    adopted_returns_by_universe = {}

    for _, log in sample_hitl_logs_df.iterrows():
        universe = log["universe"]
        date = pd.to_datetime(log["rebalance_date"])
        weight_hist = ADAPTIVE_WEIGHT_HISTORY.get(universe, pd.DataFrame()) if "ADAPTIVE_WEIGHT_HISTORY" in globals() else pd.DataFrame()
        proposed = nearest_weight_row(weight_hist, date)
        if proposed.empty:
            continue
        proposed = proposed / proposed.sum()

        if log["operator_action"] == "Constrain":
            adopted = cap_and_renormalize_weights(proposed, cap=CONFIG.get("hitl_weight_cap_after_constrain", 0.08))
        elif log["operator_action"] == "Reject":
            previous_dates = pd.to_datetime(weight_hist.index)[pd.to_datetime(weight_hist.index) < date]
            if len(previous_dates) > 0:
                adopted = weight_hist.loc[previous_dates[-1]].dropna()
                adopted = adopted / adopted.sum()
            else:
                adopted = proposed.copy()
        else:
            adopted = proposed.copy()

        proposed_r = period_returns_for_log(log, proposed)
        adopted_r = period_returns_for_log(log, adopted)

        if proposed_r.empty or adopted_r.empty:
            continue

        rows.append({
            "log_id": log["log_id"],
            "universe": universe,
            "universe_label": log["universe_label"],
            "rebalance_date": date,
            "operator_action": log["operator_action"],
            "period_days": len(adopted_r),
            "proposed_period_return": (1 + proposed_r).prod() - 1,
            "adopted_period_return": (1 + adopted_r).prod() - 1,
            "hitl_period_return_delta": ((1 + adopted_r).prod() - 1) - ((1 + proposed_r).prod() - 1),
            "proposed_period_cvar_loss": historical_cvar_loss(proposed_r, alpha=CONFIG.get("cvar_alpha", 0.95)),
            "adopted_period_cvar_loss": historical_cvar_loss(adopted_r, alpha=CONFIG.get("cvar_alpha", 0.95)),
            "proposed_period_max_drawdown": compute_max_drawdown(proposed_r),
            "adopted_period_max_drawdown": compute_max_drawdown(adopted_r),
        })

        adopted_returns_by_universe.setdefault(universe, []).append(adopted_r)

    impact = pd.DataFrame(rows)
    hitl_returns = {
        u: pd.concat(pieces).sort_index()
        for u, pieces in adopted_returns_by_universe.items()
        if len(pieces)
    }
    return impact, hitl_returns


