def _mh_get_strategy_returns(universe, strategy):
    """Return the richest available realized strategy return series."""
    if "TEN_ALGO_RETURNS" in globals() and (universe, strategy) in TEN_ALGO_RETURNS:
        return pd.Series(TEN_ALGO_RETURNS[(universe, strategy)]).dropna().sort_index()
    if "BACKTEST_RETURNS" in globals() and (universe, strategy) in BACKTEST_RETURNS:
        return pd.Series(BACKTEST_RETURNS[(universe, strategy)]).dropna().sort_index()
    return pd.Series(dtype=float)


def _mh_all_available_return_keys():
    keys = set()
    if "TEN_ALGO_RETURNS" in globals():
        keys.update(TEN_ALGO_RETURNS.keys())
    if "BACKTEST_RETURNS" in globals():
        keys.update(BACKTEST_RETURNS.keys())
    return sorted(keys, key=lambda x: (_mh_natural_universe_key(x[0]), _mh_strategy_order().index(x[1]) if x[1] in _mh_strategy_order() else 999, x[1]))


def _mh_compounded_return(r):
    r = pd.Series(r).dropna()
    return float((1 + r).prod() - 1) if len(r) else np.nan


def _mh_annualized_from_compounded(total_return, years):
    if pd.isna(total_return) or years <= 0 or total_return <= -1:
        return np.nan
    return float((1 + total_return) ** (1 / years) - 1)


def build_multi_horizon_return_table(horizons=MULTI_HORIZON_YEARS):
    rows = []
    min_coverage = float(CONFIG.get("multi_horizon_min_coverage", 0.80))
    initial_capital = float(CONFIG.get("multi_horizon_initial_capital", 100_000))

    for universe, strategy in _mh_all_available_return_keys():
        r = _mh_get_strategy_returns(universe, strategy)
        if r.empty:
            continue

        r.index = pd.to_datetime(r.index)
        r = r.sort_index().dropna()
        if r.empty:
            continue

        available_years = (r.index.max() - r.index.min()).days / 365.25
        full_total_return = _mh_compounded_return(r)
        full_annualized_return = _mh_annualized_from_compounded(full_total_return, max(available_years, 1e-9))

        for years in horizons:
            window_start = r.index.max() - pd.DateOffset(years=int(years))
            sub = r.loc[r.index >= window_start].dropna()
            required_obs = int(TRADING_DAYS * years * min_coverage)
            status = "ok" if len(sub) >= required_obs else "insufficient_history"

            if status == "ok":
                total_return = _mh_compounded_return(sub)
                annualized_return = _mh_annualized_from_compounded(total_return, years)
                terminal_value = initial_capital * (1 + total_return) if pd.notna(total_return) else np.nan
                cvar_loss = -historical_cvar(sub, CONFIG["cvar_alpha"]) if "historical_cvar" in globals() else np.nan
                max_dd = compute_max_drawdown(sub) if "compute_max_drawdown" in globals() else np.nan
                start_date = sub.index.min()
                end_date = sub.index.max()
            else:
                total_return = np.nan
                annualized_return = np.nan
                terminal_value = np.nan
                cvar_loss = np.nan
                max_dd = np.nan
                start_date = pd.NaT
                end_date = pd.NaT

            rows.append({
                "universe": universe,
                "universe_label": UNIVERSE_LABELS.get(universe, universe) if "UNIVERSE_LABELS" in globals() else universe,
                "strategy": strategy,
                "strategy_label": _mh_strategy_label(strategy),
                "horizon_years": years,
                "horizon_label": f"{years}Y",
                "status": status,
                "window_start": start_date,
                "window_end": end_date,
                "observations_used": int(len(sub)),
                "required_observations": int(required_obs),
                "available_years_in_strategy_series": available_years,
                "horizon_total_return": total_return,
                "horizon_annualized_return": annualized_return,
                "horizon_terminal_value_100k": terminal_value,
                "horizon_cvar_loss_95": cvar_loss,
                "horizon_max_drawdown": max_dd,
                "full_available_total_return": full_total_return,
                "full_available_annualized_return": full_annualized_return,
            })

    df = pd.DataFrame(rows)
    if not df.empty:
        df = df.sort_values(["universe", "strategy", "horizon_years"], key=lambda s: s.map(_mh_natural_universe_key) if s.name == "universe" else s)
    return df


