def historical_cvar_loss(r, alpha=0.95):
    """
    Positive CVaR loss helper used by HITL impact tables.
    historical_cvar(...) returns the mean tail return, usually negative.
    This function converts it into a positive loss value for reporting.
    """
    cvar = historical_cvar(r, alpha=alpha)
    return -cvar if pd.notna(cvar) else np.nan

