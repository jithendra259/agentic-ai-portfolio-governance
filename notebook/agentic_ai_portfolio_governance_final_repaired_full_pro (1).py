def sigmoid_gate(x, threshold=1.0, steepness=8.0, lambda_max=1.0):
    """Sigmoid gate used to activate graph governance during unstable regimes."""
    x = pd.Series(x).astype(float)
    return lambda_max / (1 + np.exp(-steepness * (x - threshold)))


def rolling_mean_pairwise_correlation(r, window=60):
    """Compute rolling average pairwise correlation for a universe."""
    r = r.dropna(how="any")
    values = []
    dates = []

    for end in range(window, len(r) + 1):
        chunk = r.iloc[end - window:end]
        corr = chunk.corr().values
        mask = ~np.eye(corr.shape[0], dtype=bool)
        values.append(np.nanmean(corr[mask]))
        dates.append(r.index[end - 1])

    return pd.Series(values, index=pd.to_datetime(dates), name="mean_pairwise_corr")


def rolling_drawdown_pressure(r, window=60):
    """Positive drawdown pressure derived from equal-weight rolling drawdown."""
    ew = r.mean(axis=1).dropna()
    dd_pressure = ew.rolling(window).apply(
        lambda x: -compute_max_drawdown(pd.Series(x)),
        raw=False,
    )
    return dd_pressure.rename("drawdown_pressure")


def compute_instability_panel(r, baseline_end=CONFIG["train_test_split"], window=60):
    """
    Compute a reproducible instability panel from universe returns.

    Components:
    - rolling volatility pressure
    - rolling mean pairwise correlation pressure
    - rolling drawdown pressure

    The z-score baseline uses only the train period ending at CONFIG['train_test_split'].
    """
    r = r.dropna(how="any")
    ew = r.mean(axis=1)

    vol_pressure = (ew.rolling(20).std() * np.sqrt(TRADING_DAYS)).rename("volatility_pressure")
    corr_pressure = rolling_mean_pairwise_correlation(r, window=window)
    dd_pressure = rolling_drawdown_pressure(r, window=window)

    signals = pd.concat([vol_pressure, corr_pressure, dd_pressure], axis=1).dropna()
    baseline = signals.loc[:baseline_end]
    if baseline.empty:
        baseline = signals.iloc[: max(60, int(len(signals) * 0.5))]

    mu = baseline.mean()
    sigma = baseline.std().replace(0, np.nan)
    z = ((signals - mu) / sigma).replace([np.inf, -np.inf], np.nan).fillna(0)

    panel = signals.copy()
    panel["z_volatility"] = z["volatility_pressure"]
    panel["z_correlation"] = z["mean_pairwise_corr"]
    panel["z_drawdown"] = z["drawdown_pressure"]
    panel["instability_index"] = (
        0.40 * panel["z_volatility"]
        + 0.30 * panel["z_correlation"]
        + 0.30 * panel["z_drawdown"]
    )
    panel["lambda_t"] = sigmoid_gate(
        panel["instability_index"],
        threshold=CONFIG.get("instability_threshold", 1.0),
        steepness=CONFIG.get("sigmoid_steepness", 8.0),
        lambda_max=CONFIG.get("adaptive_lambda_max", 1.0),
    )
    panel["regime"] = np.select(
        [
            panel["instability_index"] < 0.50,
            panel["instability_index"] < CONFIG.get("instability_threshold", 1.0),
        ],
        ["Calm", "Elevated"],
        default="Crisis",
    )
    return panel


