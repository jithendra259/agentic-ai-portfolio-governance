def clean_covariance_matrix(r, annualize=False):
    """Ledoit-Wolf covariance when available; sample covariance fallback."""
    clean = r.dropna(how="any")
    if clean.empty:
        return pd.DataFrame()
    if SKLEARN_LED_WOLF_AVAILABLE and clean.shape[0] > clean.shape[1] + 5:
        try:
            cov = LedoitWolf().fit(clean.values).covariance_
            cov = pd.DataFrame(cov, index=clean.columns, columns=clean.columns)
        except Exception:
            cov = clean.cov()
    else:
        cov = clean.cov()
    return cov * (TRADING_DAYS if annualize else 1.0)


def buy_and_hold_returns(r, initial_weights=None):
    """
    Buy-and-hold portfolio return series without daily rebalancing.
    It tracks wealth of initially allocated capital as asset weights drift naturally.
    """
    r = r.dropna(how="any")
    if r.empty:
        return pd.Series(dtype=float)
    if initial_weights is None:
        initial_weights = equal_weight_weights(r)
    w = pd.Series(initial_weights).reindex(r.columns).fillna(0)
    if w.sum() <= 0:
        w = equal_weight_weights(r)
    w = w / w.sum()
    asset_wealth = (1 + r).cumprod()
    portfolio_wealth = asset_wealth.dot(w)
    return portfolio_wealth.pct_change().fillna(0)


def mean_variance_weights(
    r,
    max_weight=CONFIG["max_weight"],
    risk_aversion=6.0,
    target_annual_return=CONFIG["target_annual_return"],
):
    """Long-only mean-variance / max-utility optimizer."""
    clean = r.dropna(how="any")
    cols = list(clean.columns)
    n = len(cols)
    if n == 0:
        return pd.Series(dtype=float)
    max_w = max(max_weight, 1 / n + 1e-6)

    mu = clean.mean().values
    cov = clean_covariance_matrix(clean, annualize=False).values

    w = cp.Variable(n)
    objective = cp.Maximize(mu @ w - (risk_aversion / 2.0) * cp.quad_form(w, cov))
    constraints = [cp.sum(w) == 1, w >= 0, w <= max_w]
    target_daily = daily_target_from_annual(target_annual_return)
    if target_daily is not None:
        constraints_with_target = constraints + [mu @ w >= target_daily]
    else:
        constraints_with_target = constraints

    def _solve(cons):
        problem = cp.Problem(objective, cons)
        for solver in ["CLARABEL", "ECOS", "OSQP", "SCS"]:
            if solver not in cp.installed_solvers():
                continue
            try:
                problem.solve(solver=solver, verbose=False)
                if w.value is not None:
                    weights = np.maximum(np.asarray(w.value).flatten(), 0)
                    if weights.sum() > 0:
                        return pd.Series(weights / weights.sum(), index=cols)
            except Exception:
                continue
        return None

    sol = _solve(constraints_with_target)
    if sol is not None:
        return sol
    sol = _solve(constraints)
    if sol is not None:
        return sol
    return min_variance_weights(clean, max_weight=max_weight)


def risk_parity_weights(r, max_weight=CONFIG["max_weight"]):
    """Equal-risk-contribution approximation using scipy minimize."""
    clean = r.dropna(how="any")
    cols = list(clean.columns)
    n = len(cols)
    if n == 0:
        return pd.Series(dtype=float)
    max_w = max(max_weight, 1 / n + 1e-6)
    cov = clean_covariance_matrix(clean, annualize=False).values
    cov = np.asarray(cov, dtype=float)

    def portfolio_risk_contrib(w):
        port_var = float(w @ cov @ w)
        if port_var <= 1e-18:
            return np.ones(n) / n
        marginal = cov @ w
        contrib = w * marginal / port_var
        return contrib

    def objective(w):
        contrib = portfolio_risk_contrib(w)
        target = np.ones(n) / n
        return float(((contrib - target) ** 2).sum())

    x0 = np.ones(n) / n
    bounds = [(0, max_w)] * n
    constraints = [{"type": "eq", "fun": lambda w: np.sum(w) - 1}]
    try:
        res = minimize(objective, x0=x0, method="SLSQP", bounds=bounds, constraints=constraints, options={"maxiter": 1000, "ftol": 1e-10})
        if res.success and res.x is not None and np.sum(res.x) > 0:
            w = np.maximum(res.x, 0)
            return pd.Series(w / w.sum(), index=cols)
    except Exception:
        pass
    return inverse_volatility_weights(clean)


def _hrp_quasi_diag(link):
    """Return hierarchical ordering from scipy linkage matrix."""
    link = link.astype(int)
    sort_ix = pd.Series([link[-1, 0], link[-1, 1]])
    num_items = link[-1, 3]
    while sort_ix.max() >= num_items:
        sort_ix.index = range(0, sort_ix.shape[0] * 2, 2)
        df0 = sort_ix[sort_ix >= num_items]
        i = df0.index
        j = df0.values - int(num_items)
        sort_ix[i] = link[j, 0]
        df1 = pd.Series(link[j, 1], index=i + 1)
        sort_ix = pd.concat([sort_ix, df1]).sort_index()
        sort_ix.index = range(sort_ix.shape[0])
    return sort_ix.astype(int).tolist()


def _cluster_variance(cov, cluster_items):
    cov_slice = cov.loc[cluster_items, cluster_items]
    ivp = 1.0 / np.diag(cov_slice.values)
    ivp = ivp / ivp.sum()
    return float(ivp @ cov_slice.values @ ivp)


def hierarchical_risk_parity_weights(r):
    """Simplified HRP: correlation distance, single linkage, recursive bisection."""
    clean = r.dropna(how="any")
    cols = list(clean.columns)
    n = len(cols)
    if n == 0:
        return pd.Series(dtype=float)
    if n == 1:
        return pd.Series([1.0], index=cols)

    corr = clean.corr().clip(-1, 1).fillna(0)
    cov = clean_covariance_matrix(clean, annualize=False)

    # Distance transformation used in HRP literature.
    dist = np.sqrt((1 - corr) / 2).fillna(0)
    dist_values = dist.to_numpy(copy=True)
    np.fill_diagonal(dist_values, 0)

    try:
        condensed = squareform(dist_values, checks=False)
        link = linkage(condensed, method="single")
        sort_ix = _hrp_quasi_diag(link)
        ordered = corr.index[sort_ix].tolist()
    except Exception:
        ordered = cols

    weights = pd.Series(1.0, index=ordered)
    clusters = [ordered]

    while len(clusters) > 0:
        clusters = [
            cluster[start:stop]
            for cluster in clusters
            for start, stop in ((0, len(cluster) // 2), (len(cluster) // 2, len(cluster)))
            if len(cluster) > 1
        ]
        for i in range(0, len(clusters), 2):
            if i + 1 >= len(clusters):
                continue
            c0, c1 = clusters[i], clusters[i + 1]
            var0 = _cluster_variance(cov, c0)
            var1 = _cluster_variance(cov, c1)
            alpha = 1 - var0 / (var0 + var1) if (var0 + var1) > 0 else 0.5
            weights[c0] *= alpha
            weights[c1] *= 1 - alpha

    weights = weights.reindex(cols).fillna(0)
    if weights.sum() <= 0:
        return inverse_volatility_weights(clean)
    return weights / weights.sum()


def portfolio_hhi(weights):
    w = pd.Series(weights).dropna().astype(float)
    if w.sum() <= 0:
        return np.nan
    w = w / w.sum()
    return float((w ** 2).sum())


def effective_number(weights):
    hhi = portfolio_hhi(weights)
    return float(1 / hhi) if hhi and hhi > 0 else np.nan


def weight_turnover_from_history(weight_history):
    if weight_history is None or len(weight_history) <= 1:
        return 0.0
    wh = weight_history.fillna(0)
    return float(wh.diff().abs().sum(axis=1).dropna().mean())


def graph_exposure_from_weights(weights, graph_penalty):
    w = pd.Series(weights).reindex(graph_penalty.index).fillna(0)
    if w.sum() <= 0:
        return np.nan
    w = w / w.sum()
    return float((w * graph_penalty).sum())


