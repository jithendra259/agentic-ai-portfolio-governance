from pathlib import Path
import re


REPORT_DIR = Path(__file__).resolve().parent
ROOT = REPORT_DIR.parents[1]
FIGURE_ROOT = ROOT / "notebook" / "figures_universe_analysis"
OUTPUT = REPORT_DIR / "generated_result_figures.tex"
EXPECTED_FIGURES = 121


def natural_key(value: str):
    return [
        int(part) if part.isdigit() else part.lower()
        for part in re.split(r"(\d+)", value)
    ]


def tex_escape(value: str) -> str:
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(char, char) for char in value)


def title_from_name(value: str) -> str:
    cleaned = re.sub(r"[_-]+", " ", Path(value).stem).strip()
    return cleaned[:1].upper() + cleaned[1:]


def label_from_path(path: Path) -> str:
    clean = re.sub(
        r"[^a-z0-9]+", "-", path.with_suffix("").as_posix().lower()
    ).strip("-")
    return f"fig:results:{clean}"


def figure_source(path: Path) -> str:
    return (
        "../../notebook/figures_universe_analysis/"
        + path.relative_to(FIGURE_ROOT).as_posix()
    )


def build_annex() -> str:
    pngs = sorted(
        FIGURE_ROOT.rglob("*.png"),
        key=lambda path: natural_key(path.relative_to(FIGURE_ROOT).as_posix()),
    )
    if len(pngs) != EXPECTED_FIGURES:
        raise RuntimeError(
            f"Expected {EXPECTED_FIGURES} result figures, found {len(pngs)}"
        )

    lines = [
        "% Generated by generate_result_figure_appendix.py; do not edit manually.",
        r"\section{Complete Generated Result Figure Compendium}",
        r"\label{app:complete-result-figures}",
        (
            "This annex embeds every PNG produced by the verified analysis run. "
            "Automated image-quality validation passed for all 121 files; economic "
            "interpretation remains tied to the corresponding CSV evidence and "
            "discussion in the Results chapter."
        ),
        r"\subsection{Indexed Figure Manifest}",
        (
            "The manifest provides a reproducible inventory before the full-page "
            "figures. Paths are repository-relative and grouped by evidence family."
        ),
        r"\small",
        r"\begin{longtable}{rL{4.0cm}L{7.5cm}}",
        r"\toprule",
        r"\textbf{No.} & \textbf{Evidence family} & \textbf{Figure} \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"\textbf{No.} & \textbf{Evidence family} & \textbf{Figure} \\",
        r"\midrule",
        r"\endhead",
    ]

    for number, png in enumerate(pngs, start=1):
        rel = png.relative_to(FIGURE_ROOT)
        group = rel.parts[0] if len(rel.parts) > 1 else "root"
        lines.append(
            f"{number} & {tex_escape(title_from_name(group))} & "
            f"{tex_escape(title_from_name(rel.name))} \\\\" 
        )

    lines.extend([r"\bottomrule", r"\end{longtable}", r"\normalsize"])

    current_group = None
    for png in pngs:
        rel = png.relative_to(FIGURE_ROOT)
        group = rel.parts[0] if len(rel.parts) > 1 else "root"
        if group != current_group:
            lines.extend(
                [
                    r"\clearpage",
                    rf"\subsection{{{tex_escape(title_from_name(group))}}}",
                ]
            )
            current_group = group
        source = figure_source(png)
        caption = (
            f"{title_from_name(rel.name)}. "
            "Source: completed 2014--2025 analysis run."
        )
        lines.append(
            rf"\ResultFigure{{{source}}}{{{tex_escape(caption)}}}"
            rf"{{{label_from_path(rel)}}}"
        )

    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(build_annex(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT} with {EXPECTED_FIGURES} figures")
